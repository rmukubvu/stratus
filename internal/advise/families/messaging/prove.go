// Proofs drive each option's producer path, the part quotas bite first:
// SendMessage, Publish, PutEvents or PutRecord at the peak rate, after a
// setup that creates the queue, topic, rule or stream in the proof's own
// account. Consumers are not driven; their throughput is the rules' job.

const (
	// maxProofPayload caps the bytes a proof sends per message, so a
	// proof of large messages measures quotas rather than the laptop's
	// network. Size limits are checked by the rules.
	maxProofPayload = 64 * bytesPerKiB
	maxEventTargets = 5
	minPreVUs       = 5
	maxPreVUs       = 500
	minMaxVUs       = 50
	maxMaxVUs       = 2000
	vusPerPreRate   = 20 // one pre-allocated VU per 20 requests/s
	vusPerMaxRate   = 2
)

// ProofLoad implements advise.Prover.
func (Family) ProofLoad(r advise.Requirements) (float64, string) {
	w := workloadFrom(r)
	return w.peak, w.region
}

// Proof implements advise.Prover.
func (f Family) Proof(option string, r advise.Requirements, t advise.ProofTarget) advise.ProofScript {
	w := workloadFrom(r)
	switch option {
	case SQSStandard:
		return script(t, w, sqsSetup, sqsProduce, op("sqs", "CreateQueue"), op("sqs", "SendMessage"))
	case SNSFanout:
		return script(t, w, snsSetup, snsProduce, op("sns", "CreateTopic"), op("sqs", "CreateQueue"), op("sns", "Subscribe"), op("sns", "Publish"))
	case EventBridge:
		return script(t, w, eventsSetup, eventsProduce, op("sqs", "CreateQueue"), op("events", "PutRule"), op("events", "PutTargets"), op("events", "PutEvents"))
	case Kinesis:
		return script(t, w, kinesisSetup, kinesisProduce, op("kinesis", "CreateStream"), op("kinesis", "PutRecord"))
	case SQSFIFO:
		return advise.ProofScript{Unprovable: "Stratus does not implement FIFO queues yet, so a FIFO proof cannot run; the FIFO quotas are checked by the rules."}
	case MSK:
		return advise.ProofScript{Unprovable: "Proving MSK needs a Kafka client, which a k6 HTTP script cannot drive. Stratus runs real Kafka for MSK clusters (docs/msk.md) for testing with your own clients."}
	}
	return advise.ProofScript{Unprovable: "The messaging family has no proof for " + option + "."}
}

func op(service, name string) advise.Operation { return advise.Operation{Service: service, Name: name} }

// proofData fills the script template. Strings that come from answers
// are JSON-encoded, so they are safe inside JavaScript.
type proofData struct {
	Endpoint, Account, Region, Name string // JSON string literals
	Rate, Seconds                   int
	PreVUs, MaxVUs                  int
	Payload                         int
	Consumers, Targets, Shards      int
	Setup, Produce                  string
}

func script(t advise.ProofTarget, w workload, setup, produce string, ops ...advise.Operation) advise.ProofScript {
	rate := int(t.Rate)
	shards := 1
	if w.peak > 0 {
		// Size the stream for the proof's rate, as provisioned mode would.
		shards = shardsFor(workload{peak: t.Rate, sizeBytes: w.sizeBytes}, 1000, 1<<20)
	}
	d := proofData{
		Account: jsString(t.Account), Region: jsString(t.Region), Name: jsString("proof-" + t.Name),
		Rate: rate, Seconds: int(t.Duration.Seconds()),
		PreVUs:    clamp(rate/vusPerPreRate, minPreVUs, maxPreVUs),
		MaxVUs:    clamp(rate/vusPerMaxRate, minMaxVUs, maxMaxVUs),
		Payload:   int(math.Max(1, math.Min(w.sizeBytes, maxProofPayload))),
		Consumers: max(1, w.consumers), Targets: min(max(1, w.consumers), maxEventTargets),
		Shards: shards, Setup: setup, Produce: produce,
	}
	var b bytes.Buffer
	if err := proofTemplate.Execute(&b, d); err != nil {
		panic(err) // static template; covered by tests
	}
	return advise.ProofScript{Operations: ops, Script: b.String()}
}

func jsString(s string) string {
	raw, _ := json.Marshal(s)
	return string(raw)
}

func clamp(v, lo, hi int) int { return max(lo, min(v, hi)) }

var proofTemplate = template.Must(template.New("proof").Parse(`// Generated by 'stratus advise prove'. Drives the producer path at the
// stated peak against Stratus, in a throwaway account, while Stratus
// records the run under the aws-default limits profile.
//
//   stratus load run --limits aws-default -- k6 run this-script.js
import http from "k6/http";
import { check } from "k6";
import encoding from "k6/encoding";

const endpoint = __ENV.STRATUS_ENDPOINT || "http://localhost:4566";
const account = {{.Account}};
const region = {{.Region}};
const name = {{.Name}};
// Payloads are capped at 64 KiB so the proof measures quotas, not the
// network; size limits are checked by the assessment's rules.
const body = "x".repeat({{.Payload}});

export const options = {
  scenarios: {
    produce: {
      executor: "constant-arrival-rate",
      rate: {{.Rate}},
      timeUnit: "1s",
      duration: "{{.Seconds}}s",
      preAllocatedVUs: {{.PreVUs}},
      maxVUs: {{.MaxVUs}},
    },
  },
};

// Stratus accepts any signature unless strict SigV4 is on; the access key
// is the account, so this proof's resources and quotas are its own.
function auth(service) {
  return "AWS4-HMAC-SHA256 Credential=" + account + "/20260101/" + region + "/" + service + "/aws4_request, SignedHeaders=host, Signature=0";
}

function json(service, target, version, payload) {
  return http.post(endpoint, JSON.stringify(payload), {
    headers: { "Content-Type": "application/x-amz-json-" + version, "X-Amz-Target": target, Authorization: auth(service) },
    tags: { operation: target.split(".")[1] },
  });
}

function query(service, params) {
  const form = Object.keys(params).map((k) => encodeURIComponent(k) + "=" + encodeURIComponent(params[k])).join("&");
  return http.post(endpoint, form, {
    headers: { "Content-Type": "application/x-www-form-urlencoded", Authorization: auth(service) },
    tags: { operation: params.Action },
  });
}

function must(res, what) {
  if (res.status !== 200) {
    throw new Error(what + " failed: " + res.status + " " + res.body);
  }
  return res;
}

function createQueue(queue) {
  return must(json("sqs", "AmazonSQS.CreateQueue", "1.0", { QueueName: queue }), "CreateQueue").json("QueueUrl");
}

function queueArn(queue) {
  return "arn:aws:sqs:" + region + ":" + account + ":" + queue;
}

function accepted(res) {
  check(res, { "accepted": (r) => r.status === 200, "not throttled": (r) => r.status !== 429 && !String(r.body).includes("Throttl") });
}

const consumers = {{.Consumers}};
const targets = {{.Targets}};
const shards = {{.Shards}};

{{.Setup}}

{{.Produce}}
`))

const sqsSetup = `export function setup() {
  return { queueUrl: createQueue(name) };
}`

const sqsProduce = `export default function (s) {
  accepted(json("sqs", "AmazonSQS.SendMessage", "1.0", { QueueUrl: s.queueUrl, MessageBody: body }));
}`

const snsSetup = `export function setup() {
  const created = must(query("sns", { Action: "CreateTopic", Version: "2010-03-31", Name: name }), "CreateTopic");
  const topicArn = /<TopicArn>([^<]+)<\/TopicArn>/.exec(created.body)[1];
  for (let i = 0; i < consumers; i++) {
    const queue = name + "-" + i;
    createQueue(queue);
    must(query("sns", { Action: "Subscribe", Version: "2010-03-31", TopicArn: topicArn, Protocol: "sqs", Endpoint: queueArn(queue) }), "Subscribe");
  }
  return { topicArn: topicArn };
}`

const snsProduce = `export default function (s) {
  accepted(query("sns", { Action: "Publish", Version: "2010-03-31", TopicArn: s.topicArn, Message: body }));
}`

const eventsSetup = `export function setup() {
  must(json("events", "AWSEvents.PutRule", "1.1", { Name: name, EventPattern: JSON.stringify({ source: [name] }) }), "PutRule");
  const list = [];
  for (let i = 0; i < targets; i++) {
    const queue = name + "-" + i;
    createQueue(queue);
    list.push({ Id: "q" + i, Arn: queueArn(queue) });
  }
  must(json("events", "AWSEvents.PutTargets", "1.1", { Rule: name, Targets: list }), "PutTargets");
  return {};
}`

const eventsProduce = `export default function () {
  const detail = JSON.stringify({ body: body });
  accepted(json("events", "AWSEvents.PutEvents", "1.1", { Entries: [{ Source: name, DetailType: "proof", Detail: detail }] }));
}`

const kinesisSetup = `export function setup() {
  must(json("kinesis", "Kinesis_20131202.CreateStream", "1.1", { StreamName: name, ShardCount: shards }), "CreateStream");
  return {};
}`

const kinesisProduce = `const data = encoding.b64encode(body);
export default function () {
  accepted(json("kinesis", "Kinesis_20131202.PutRecord", "1.1", { StreamName: name, Data: data, PartitionKey: "key-" + Math.floor(Math.random() * 1000) }));
}`
