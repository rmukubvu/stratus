package advise

import (
	"fmt"
	"math"
	"sort"
	"strconv"
	"strings"
)

// RenderADR writes a decision as a Markdown architecture decision record
// in the MADR layout. It is rendered from the decision every time, so it
// cannot drift from the answers and assessment it describes.
func RenderADR(d Decision, f Family) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	opts := map[string]Option{}
	for _, o := range f.Options() {
		opts[o.ID] = o
	}
	name := func(id string) string {
		if o, ok := opts[id]; ok {
			return o.Name
		}
		return id
	}

	w("# %s\n\n", escape(d.Title))
	w("- Status: %s\n", adrStatus(d.Status))
	date := d.UpdatedAt
	if d.DecidedAt != nil {
		date = *d.DecidedAt
	}
	w("- Date: %s\n", date.Format("2006-01-02"))
	w("- Decision family: %s\n", f.Title())
	w("- Record: `%s`, generated by `stratus advise`\n\n", d.ID)

	w("## Context and requirements\n\n")
	w("| Requirement | Answer | Source |\n| --- | --- | --- |\n")
	req := d.Requirements(f)
	for _, q := range questionsOf(f) {
		src := "stated"
		if req.Assumed(q.ID) {
			src = "assumed (default)"
		}
		w("| %s | %s | %s |\n", escape(q.Prompt), escape(q.Label(req.Value(q.ID))), src)
	}
	w("\n")

	if len(d.Assessments) == 0 {
		w("## Options considered\n\nNot assessed yet. Run `stratus advise assess %s`.\n", d.ID)
		return b.String()
	}

	w("## Options considered\n\n")
	// pricedAt is any estimate, for the cost column; datedAt is one that
	// found prices, for their date and source.
	var pricedAt, datedAt *Estimate
	for _, a := range d.Assessments {
		if a.Cost != nil && pricedAt == nil {
			pricedAt = a.Cost
		}
		if a.Cost != nil && a.Cost.PricesAsOf != "" && datedAt == nil {
			datedAt = a.Cost
		}
	}
	if pricedAt != nil {
		w("| Rank | Option | Verdict | Fit | Ops overhead | Est. monthly cost |\n| --- | --- | --- | --- | --- | --- |\n")
	} else {
		w("| Rank | Option | Verdict | Fit | Ops overhead |\n| --- | --- | --- | --- | --- |\n")
	}
	for i, a := range d.Assessments {
		w("| %d | %s | %s | %d/100 | %d/15 |", i+1, name(a.Option), verdictLabel(a.Verdict), a.Score, opts[a.Option].Ops.Total())
		if pricedAt != nil {
			w(" %s |", monthly(a.Cost))
		}
		w("\n")
	}
	w("\n")
	if datedAt != nil {
		w("Costs are estimates at the stated average rate from AWS on-demand list prices for %s, published %s, before the free tier, taxes and data transfer. \"At least\" marks an estimate missing a price.\n\n", datedAt.Region, datedAt.PricesAsOf)
	}
	sources := map[string]bool{}
	for _, a := range d.Assessments {
		w("### %s: %s\n\n", name(a.Option), verdictLabel(a.Verdict))
		if s := opts[a.Option].Summary; s != "" {
			w("%s\n\n", s)
		}
		for _, r := range a.Reasons {
			w("- %s %s%s\n", reasonMark(r.Kind), r.Text, cite(r.Citation))
			if r.Citation != nil && r.Citation.URL != "" {
				sources[r.Citation.URL] = true
			}
		}
		w("\n")
	}

	w("## Decision\n\n")
	if d.Status == StatusDecided {
		w("Chosen option: **%s**", name(d.Chosen))
		if d.Rationale != "" {
			w(", because %s", strings.TrimSuffix(d.Rationale, "."))
		}
		w(".\n\n")
	} else if a, ok := d.Recommended(); ok {
		w("No option chosen yet. Ranked first: **%s**.\n\n", name(a.Option))
	} else {
		w("Every option was ruled out. Revisit the requirements marked as assumed, or widen the family.\n\n")
	}

	shown := d.Chosen
	if shown == "" {
		if a, ok := d.Recommended(); ok {
			shown = a.Option
		}
	}
	if a, ok := d.assessment(shown); ok {
		w("## Consequences\n\n")
		for _, r := range a.Reasons {
			switch r.Kind {
			case ReasonStrength:
				w("- Good: %s\n", r.Text)
			case ReasonCaveat:
				w("- Watch: %s\n", r.Text)
			}
		}
		w("\nOperational overhead of %s (%d/15):\n\n", name(shown), opts[shown].Ops.Total())
		w("| Dimension | Score | Why |\n| --- | --- | --- |\n")
		for _, s := range opts[shown].Ops.Dimensions() {
			w("| %s | %d/3 | %s |\n", s.Name, s.Score, escape(s.Reason))
		}
		w("\n")
		if a.Cost != nil {
			writeCost(w, name(shown), *a.Cost)
		}
	}

	w("## Notes\n\n")
	w("- Verdicts come from Stratus's rules for the %s family, checked against AWS's documented default quotas at the stated peak. They are not a load test.\n", strings.ToLower(f.Title()))
	w("- Ops overhead scores are judgement, kept in Stratus's source for review.\n")
	if datedAt != nil {
		w("- Prices come from a snapshot of AWS's public price list (<%s>) published %s and shipped in Stratus; rerun with a newer Stratus for newer prices.\n", datedAt.Source, datedAt.PricesAsOf)
	}
	if len(sources) > 0 {
		urls := make([]string, 0, len(sources))
		for u := range sources {
			urls = append(urls, u)
		}
		sort.Strings(urls)
		w("- Sources:\n")
		for _, u := range urls {
			w("  - <%s>\n", u)
		}
	}
	return b.String()
}

// writeCost renders an option's estimate: its lines, total and the
// assumptions behind the usage model.
func writeCost(w func(string, ...any), option string, e Estimate) {
	w("Estimated monthly cost of %s in %s:\n\n", option, e.Region)
	w("| Item | Quantity | Monthly |\n| --- | --- | --- |\n")
	for _, l := range e.Lines {
		w("| %s | %s %s | %s |\n", escape(l.Item), quantity(l.Quantity), l.Unit, usd(l.USD))
	}
	for _, id := range e.Unpriced {
		w("| `%s` | no price for %s in the snapshot | not counted |\n", id, e.Region)
	}
	w("| **Total** | | **%s** |\n\n", monthly(&e))
	for _, a := range e.Assumptions {
		w("- Assumes: %s\n", a)
	}
	if len(e.Assumptions) > 0 {
		w("\n")
	}
}

// monthly prints an estimate's total, "at least" when a price is missing.
func monthly(e *Estimate) string {
	switch {
	case e == nil:
		return "not estimated"
	case !e.Complete():
		return "at least " + usd(e.MonthlyUSD)
	default:
		return usd(e.MonthlyUSD)
	}
}

// usd prints dollars to the cent, with thousands separators.
func usd(v float64) string {
	cents := int64(math.Round(v * 100))
	return "$" + thousands(cents/100) + fmt.Sprintf(".%02d", cents%100)
}

// quantity prints a usage quantity: whole numbers with separators, small
// ones to two decimals.
func quantity(v float64) string {
	if v >= 100 {
		return thousands(int64(math.Round(v)))
	}
	return strconv.FormatFloat(math.Round(v*100)/100, 'f', -1, 64)
}

func thousands(n int64) string {
	s := strconv.FormatInt(n, 10)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

func adrStatus(s Status) string {
	if s == StatusDecided {
		return "accepted"
	}
	return "proposed"
}

func verdictLabel(v Verdict) string {
	switch v {
	case VerdictFits:
		return "fits"
	case VerdictFitsCaveats:
		return "fits, with caveats"
	default:
		return "ruled out"
	}
}

func reasonMark(k ReasonKind) string {
	switch k {
	case ReasonRuledOut:
		return "**Ruled out:**"
	case ReasonCaveat:
		return "**Caveat:**"
	case ReasonStrength:
		return "**Strength:**"
	default:
		return "**Not checked:**"
	}
}

func cite(c *Citation) string {
	if c == nil {
		return ""
	}
	switch {
	case c.QuotaID != "" && c.URL != "":
		return fmt.Sprintf(" ([%s](%s))", c.QuotaID, c.URL)
	case c.URL != "":
		return fmt.Sprintf(" ([source](%s))", c.URL)
	case c.QuotaID != "":
		return fmt.Sprintf(" (quota `%s`)", c.QuotaID)
	}
	return ""
}

func escape(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
