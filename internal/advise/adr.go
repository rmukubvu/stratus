package advise

import (
	"fmt"
	"math"
	"sort"
	"strconv"
	"strings"
)

// RenderADR writes a decision as a Markdown architecture decision record
// in the MADR layout. It is rendered from the decision every time, so it
// cannot drift from the answers and assessment it describes.
func RenderADR(d Decision, f Family) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	opts := map[string]Option{}
	for _, o := range f.Options() {
		opts[o.ID] = o
	}
	name := func(id string) string {
		if o, ok := opts[id]; ok {
			return o.Name
		}
		return id
	}

	w("# %s\n\n", escape(d.Title))
	w("- Status: %s\n", adrStatus(d.Status))
	date := d.UpdatedAt
	if d.DecidedAt != nil {
		date = *d.DecidedAt
	}
	w("- Date: %s\n", date.Format("2006-01-02"))
	w("- Decision family: %s\n", f.Title())
	w("- Record: `%s`, generated by `stratus advise`\n\n", d.ID)

	w("## Context and requirements\n\n")
	w("| Requirement | Answer | Source |\n| --- | --- | --- |\n")
	req := d.Requirements(f)
	for _, q := range questionsOf(f) {
		src := "stated"
		if req.Assumed(q.ID) {
			src = "assumed (default)"
		}
		w("| %s | %s | %s |\n", escape(q.Prompt), escape(q.Label(req.Value(q.ID))), src)
	}
	w("\n")

	if len(d.Assessments) == 0 {
		w("## Options considered\n\nNot assessed yet. Run `stratus advise assess %s`.\n", d.ID)
		return b.String()
	}

	w("## Options considered\n\n")
	// pricedAt is any estimate, for the cost column; datedAt is one that
	// found prices, for their date and source.
	var pricedAt, datedAt *Estimate
	for _, a := range d.Assessments {
		if a.Cost != nil && pricedAt == nil {
			pricedAt = a.Cost
		}
		if a.Cost != nil && a.Cost.PricesAsOf != "" && datedAt == nil {
			datedAt = a.Cost
		}
	}
	proved := len(d.Evidence) > 0
	w("| Rank | Option | Verdict | Fit | Ops overhead |")
	if pricedAt != nil {
		w(" Est. monthly cost |")
	}
	if proved {
		w(" Load proof |")
	}
	w("\n| --- | --- | --- | --- | --- |")
	if pricedAt != nil {
		w(" --- |")
	}
	if proved {
		w(" --- |")
	}
	w("\n")
	for i, a := range d.Assessments {
		w("| %d | %s | %s | %d/100 | %d/15 |", i+1, name(a.Option), verdictLabel(a.Verdict), a.Score, opts[a.Option].Ops.Total())
		if pricedAt != nil {
			w(" %s |", monthly(a.Cost))
		}
		if proved {
			w(" %s |", proofCell(d, a.Option))
		}
		w("\n")
	}
	w("\n")
	if datedAt != nil {
		w("Costs are estimates at the stated average rate from AWS on-demand list prices for %s, published %s, before the free tier, taxes and data transfer. \"At least\" marks an estimate missing a price.\n\n", datedAt.Region, datedAt.PricesAsOf)
	}
	sources := map[string]bool{}
	for _, a := range d.Assessments {
		w("### %s: %s\n\n", name(a.Option), verdictLabel(a.Verdict))
		if s := opts[a.Option].Summary; s != "" {
			w("%s\n\n", s)
		}
		for _, r := range a.Reasons {
			w("- %s %s%s\n", reasonMark(r.Kind), r.Text, cite(r.Citation))
			if r.Citation != nil && r.Citation.URL != "" {
				sources[r.Citation.URL] = true
			}
		}
		if e, ok := d.EvidenceFor(a.Option); ok {
			w("- **Load proof:** %s\n", proofSentence(e))
		}
		w("\n")
	}

	w("## Decision\n\n")
	if d.Status == StatusDecided {
		w("Chosen option: **%s**", name(d.Chosen))
		if d.Rationale != "" {
			w(", because %s", strings.TrimSuffix(d.Rationale, "."))
		}
		w(".\n\n")
	} else if a, ok := d.Recommended(); ok {
		w("No option chosen yet. Ranked first: **%s**.\n\n", name(a.Option))
	} else {
		w("Every option was ruled out. Revisit the requirements marked as assumed, or widen the family.\n\n")
	}

	shown := d.Chosen
	if shown == "" {
		if a, ok := d.Recommended(); ok {
			shown = a.Option
		}
	}
	if a, ok := d.assessment(shown); ok {
		w("## Consequences\n\n")
		for _, r := range a.Reasons {
			switch r.Kind {
			case ReasonStrength:
				w("- Good: %s\n", r.Text)
			case ReasonCaveat:
				w("- Watch: %s\n", r.Text)
			}
		}
		w("\nOperational overhead of %s (%d/15):\n\n", name(shown), opts[shown].Ops.Total())
		w("| Dimension | Score | Why |\n| --- | --- | --- |\n")
		for _, s := range opts[shown].Ops.Dimensions() {
			w("| %s | %d/3 | %s |\n", s.Name, s.Score, escape(s.Reason))
		}
		w("\n")
		if a.Cost != nil {
			writeCost(w, name(shown), *a.Cost)
		}
	}
	writeInfrastructure(w, d, f, shown, name)

	w("## Notes\n\n")
	w("- Verdicts come from Stratus's rules for the %s family, checked against AWS's documented default quotas at the stated peak.", strings.ToLower(f.Title()))
	if !proved {
		w(" They are not a load test; `stratus advise prove %s` runs one.", d.ID)
	}
	w("\n")
	w("- Ops overhead scores are judgement, kept in Stratus's source for review.\n")
	if proved {
		w("- Load proofs drove each option's producer path (send, publish or put) against Stratus at the target rate for the stated time, in a throwaway account, under the aws-default limits profile. They exercise the quotas Stratus enforces (docs/limits.md) and the APIs' behaviour, not AWS's latency; quotas Stratus does not enforce, such as Kinesis per-shard writes, are covered by the rules above.\n")
	}
	if datedAt != nil {
		w("- Prices come from a snapshot of AWS's public price list (<%s>) published %s and shipped in Stratus; rerun with a newer Stratus for newer prices.\n", datedAt.Source, datedAt.PricesAsOf)
	}
	if len(sources) > 0 {
		urls := make([]string, 0, len(sources))
		for u := range sources {
			urls = append(urls, u)
		}
		sort.Strings(urls)
		w("- Sources:\n")
		for _, u := range urls {
			w("  - <%s>\n", u)
		}
	}
	return b.String()
}

// writeInfrastructure points at the Terraform for the shown option and
// reports every recorded test deploy.
func writeInfrastructure(w func(string, ...any), d Decision, f Family, shown string, name func(string) string) {
	m, err := d.Terraform(f, shown)
	if err != nil && len(d.Deployments) == 0 {
		return
	}
	w("## Infrastructure\n\n")
	if err == nil {
		w("`stratus advise terraform %s --out infra` writes Terraform for %s: a root module with versions.tf, variables.tf, main.tf and outputs.tf, sized from the requirements above.", d.ID, name(m.Option))
		_, deployed := d.DeploymentFor(m.Option)
		switch {
		case !m.Deployable:
			w(" %s", m.Reason)
		case !deployed:
			w(" It has not been test-deployed; `stratus advise terraform %s --deploy` applies it to Stratus, re-plans it and destroys it.", d.ID)
		}
		w("\n\n")
	}
	for _, dep := range d.Deployments {
		w("- **Test deploy of %s:** %s\n", name(dep.Option), deploySentence(dep))
	}
	if len(d.Deployments) > 0 {
		w("\n")
	}
}

func deploySentence(dep Deployment) string {
	date := dep.RecordedAt.Format("2006-01-02")
	var s string
	switch dep.Outcome {
	case DeployPassed:
		s = fmt.Sprintf("on %s, %s applied %s to Stratus, a plan straight after found nothing to change, and destroy removed everything.", date, dep.Tool, resources(dep.Resources))
	case DeployDrifted:
		s = fmt.Sprintf("on %s, %s applied %s to Stratus and destroyed everything, but a plan straight after the apply wanted changes, so a resource reads back differently than it was written.", date, dep.Tool, resources(dep.Resources))
	default:
		s = fmt.Sprintf("failed on %s.", date)
	}
	if dep.Detail != "" {
		s += " " + strings.TrimSuffix(firstLine(dep.Detail), ".") + "."
	}
	return s
}

func resources(n int) string {
	if n == 1 {
		return "1 resource"
	}
	return fmt.Sprintf("%d resources", n)
}

func firstLine(s string) string {
	line, _, _ := strings.Cut(strings.TrimSpace(s), "\n")
	return line
}

// proofCell is an option's load proof in the ranking table.
func proofCell(d Decision, option string) string {
	e, ok := d.EvidenceFor(option)
	if !ok {
		return "not run"
	}
	return fmt.Sprintf("%s at %s/s", proofLabel(e.Verdict), quantity(e.TargetRate))
}

func proofLabel(v ProofVerdict) string {
	switch v {
	case ProofHeld:
		return "held"
	case ProofThrottled:
		return "throttled"
	case ProofFailed:
		return "failed"
	default:
		return "fell short"
	}
}

// proofSentence describes a proof for an option's section.
func proofSentence(e Evidence) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s at %s/s for %ss", proofLabel(e.Verdict), quantity(e.TargetRate), quantity(math.Round(e.DurationSeconds)))
	if e.Scale != 1 {
		fmt.Fprintf(&b, " (%s of the peak, quotas scaled alike)", strconv.FormatFloat(e.Scale, 'g', -1, 64))
	}
	fmt.Fprintf(&b, ": %s requests, %s/s on average, %s throttled, %s errors, p99 %s ms",
		quantity(float64(e.Requests)), quantity(e.PerSecond), quantity(float64(e.Throttled)), quantity(float64(e.Errors)), quantity(e.P99MS))
	if len(e.ThrottledBy) > 0 {
		fmt.Fprintf(&b, "; throttled by `%s`", strings.Join(e.ThrottledBy, "`, `"))
	}
	fmt.Fprintf(&b, " (run `%s`", e.RunID)
	if e.Account != "" {
		fmt.Fprintf(&b, ", account %s", e.Account)
	}
	b.WriteString(").")
	if e.Verdict == ProofShort {
		b.WriteString(" The run did not reach the target rate, which says more about the machine running it than about AWS; prove again with a lower scale.")
	}
	for _, f := range e.Findings {
		fmt.Fprintf(&b, " Finding: %s.", strings.TrimSuffix(f, "."))
	}
	return b.String()
}

// writeCost renders an option's estimate: its lines, total and the
// assumptions behind the usage model.
func writeCost(w func(string, ...any), option string, e Estimate) {
	w("Estimated monthly cost of %s in %s:\n\n", option, e.Region)
	w("| Item | Quantity | Monthly |\n| --- | --- | --- |\n")
	for _, l := range e.Lines {
		w("| %s | %s %s | %s |\n", escape(l.Item), quantity(l.Quantity), l.Unit, usd(l.USD))
	}
	for _, id := range e.Unpriced {
		w("| `%s` | no price for %s in the snapshot | not counted |\n", id, e.Region)
	}
	w("| **Total** | | **%s** |\n\n", monthly(&e))
	for _, a := range e.Assumptions {
		w("- Assumes: %s\n", a)
	}
	if len(e.Assumptions) > 0 {
		w("\n")
	}
}

// monthly prints an estimate's total, "at least" when a price is missing.
func monthly(e *Estimate) string {
	switch {
	case e == nil:
		return "not estimated"
	case !e.Complete():
		return "at least " + usd(e.MonthlyUSD)
	default:
		return usd(e.MonthlyUSD)
	}
}

// usd prints dollars to the cent, with thousands separators.
func usd(v float64) string {
	cents := int64(math.Round(v * 100))
	return "$" + thousands(cents/100) + fmt.Sprintf(".%02d", cents%100)
}

// quantity prints a usage quantity: whole numbers with separators, small
// ones to two decimals.
func quantity(v float64) string {
	if v >= 100 {
		return thousands(int64(math.Round(v)))
	}
	return strconv.FormatFloat(math.Round(v*100)/100, 'f', -1, 64)
}

func thousands(n int64) string {
	s := strconv.FormatInt(n, 10)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

func adrStatus(s Status) string {
	if s == StatusDecided {
		return "accepted"
	}
	return "proposed"
}

func verdictLabel(v Verdict) string {
	switch v {
	case VerdictFits:
		return "fits"
	case VerdictFitsCaveats:
		return "fits, with caveats"
	default:
		return "ruled out"
	}
}

func reasonMark(k ReasonKind) string {
	switch k {
	case ReasonRuledOut:
		return "**Ruled out:**"
	case ReasonCaveat:
		return "**Caveat:**"
	case ReasonStrength:
		return "**Strength:**"
	default:
		return "**Not checked:**"
	}
}

func cite(c *Citation) string {
	if c == nil {
		return ""
	}
	switch {
	case c.QuotaID != "" && c.URL != "":
		return fmt.Sprintf(" ([%s](%s))", c.QuotaID, c.URL)
	case c.URL != "":
		return fmt.Sprintf(" ([source](%s))", c.URL)
	case c.QuotaID != "":
		return fmt.Sprintf(" (quota `%s`)", c.QuotaID)
	}
	return ""
}

func escape(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
